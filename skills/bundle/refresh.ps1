[CmdletBinding()]
param(
  [string]$RepoRoot
)

$ErrorActionPreference = 'Stop'

if (-not $RepoRoot) {
  $candidates = @(
    (Join-Path $PSScriptRoot '..\..'),
    (Join-Path $PSScriptRoot '..\..\..')
  )
  foreach ($candidate in $candidates) {
    if (Test-Path -LiteralPath (Join-Path $candidate 'CMakeLists.txt')) {
      $RepoRoot = (Resolve-Path $candidate).Path
      break
    }
  }
}
if (-not $RepoRoot) {
  throw "cannot locate tugmcp repository root; pass -RepoRoot <path>"
}

$bundle = $PSScriptRoot
$files = @(
  'CMakeLists.txt',
  'cmake/doctest.cmake',
  'cmake/verify_hashes.cmake',
  'cmake/verify_manifest.cmake',
  'tests/CMakeLists.txt',
  'tests/conformance/expected_failures.yaml',
  'tests/amalgamation/CMakeLists.txt',
  'tests/amalgamation/require_external.cmake',
  'tests/amalgamation/core.sha256',
  'tests/amalgamation/http.sha256',
  'tests/amalgamation/http_tls.sha256'
)

if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot 'CMakeLists.txt'))) {
  throw "not a tugmcp repository root: $RepoRoot"
}

$sha = [System.Security.Cryptography.SHA256]::Create()
$rows = @()
try {
  foreach ($relative in $files) {
    $source = Join-Path $RepoRoot $relative
    if (-not (Test-Path -LiteralPath $source)) {
      throw "missing source file: $source"
    }

    $destination = Join-Path $bundle $relative
    $directory = Split-Path -Parent $destination
    if (-not (Test-Path -LiteralPath $directory)) {
      New-Item -ItemType Directory -Force -Path $directory | Out-Null
    }

    # Normalize to LF so snapshot hashes stay stable across Windows checkouts.
    $text = [System.IO.File]::ReadAllText($source)
    $text = $text.Replace("`r`n", "`n")
    [System.IO.File]::WriteAllText(
      $destination,
      $text,
      (New-Object System.Text.UTF8Encoding($false))
    )

    $stream = [System.IO.File]::OpenRead($destination)
    try {
      $hash = ($sha.ComputeHash($stream) | ForEach-Object { $_.ToString('x2') }) -join ''
    } finally {
      $stream.Dispose()
    }
    $rows += [pscustomobject]@{ Path = ($relative -replace '\\', '/'); Hash = $hash }
  }
} finally {
  $sha.Dispose()
}

$commit = (& git -C $RepoRoot rev-parse --short HEAD).Trim()
$remote = (& git -C $RepoRoot remote get-url github 2>$null)
if (-not $remote) {
  $remote = 'https://github.com/mrchipset/tugmcp'
}
$remote = $remote -replace '^git@github\.com:', 'https://github.com/' -replace '\.git$', ''
$date = Get-Date -Format 'yyyy-MM-dd'

$lines = @(
  '# Bundle manifest',
  '',
  "- Source: $remote",
  "- Commit: ``$commit``",
  "- Generated: $date",
  '',
  'This file is generated by `refresh.ps1`; do not edit by hand.',
  '',
  '| Bundle file | SHA256 |',
  '|---|---|'
)
foreach ($row in $rows) {
  $lines += "| ``$($row.Path)`` | ``$($row.Hash)`` |"
}

$manifest = ($lines -join "`n") + "`n"
$manifestPath = Join-Path $bundle 'MANIFEST.md'
[System.IO.File]::WriteAllText($manifestPath, $manifest, (New-Object System.Text.UTF8Encoding($false)))

Write-Output "bundle refreshed: $($rows.Count) files, commit $commit"
